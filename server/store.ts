// Helper to compute lead score (0-100) based on budget, service, and data completeness
export function calculateLeadScore(budget: number, service: LeadService, phone: boolean, company: string): number {
  let score = 30; // base score
  if (budget >= 50000) score += 35;
  else if (budget >= 25000) score += 25;
  else if (budget >= 10000) score += 15;
  else if (budget >= 5000) score += 10;

  if (service === 'full_stack_build' || service === 'shopify_dev') score += 15;
  else if (service === 'performance_marketing') score += 10;

  if (phone) score += 10;
  if (company && company.length > 3) score += 10;

  return Math.min(100, Math.max(10, score));
}

