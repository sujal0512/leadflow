// In-Memory Database State
class DataStore {
  users: User[] = [...INITIAL_USERS];
  leads: Lead[] = [...INITIAL_LEADS];
  notes: LeadNote[] = [...INITIAL_NOTES];
  activities: LeadActivity[] = [...INITIAL_ACTIVITIES];
  emails: EmailLog[] = [];

  reset() {
    this.users = JSON.parse(JSON.stringify(INITIAL_USERS));
    this.leads = JSON.parse(JSON.stringify(INITIAL_LEADS));
    this.notes = JSON.parse(JSON.stringify(INITIAL_NOTES));
    this.activities = JSON.parse(JSON.stringify(INITIAL_ACTIVITIES));
    this.emails = [];
  }

  logEmail(leadId: string, leadCompany: string, recipient: string, subject: string, body: string) {
    const email: EmailLog = {
      id: `email_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      leadId,
      leadCompany,
      recipient,
      subject,
      body,
      timestamp: new Date().toISOString(),
    };
    this.emails.unshift(email);
    return email;
  }

  logActivity(leadId: string, userId: string, userName: string, action: string, details: string) {
    const act: LeadActivity = {
      id: `act_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      leadId,
      userId,
      userName,
      action,
      details,
      timestamp: new Date().toISOString(),
    };
    this.activities.unshift(act);
    return act;
  }
}

